int Pieces::Block(int piece, int rotation, int x, int y) {
  if (piece < 0 || piece >= kPieceCount) return 0;
  rotation &= 3;
  if (x < 0 || x >= kSize || y < 0 || y >= kSize) return 0;
  return kPieces[piece][rotation][y][x];
}
